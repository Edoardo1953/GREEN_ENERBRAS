function t(key, fallback = '') {
    const lang = (typeof window.currentLang !== 'undefined' ? window.currentLang : (typeof currentLang !== 'undefined' ? currentLang : localStorage.getItem('appLang') || 'it'));
    if (typeof translations !== 'undefined' && translations[lang] && translations[lang][key]) {
        return translations[lang][key];
    }
    if (typeof translations !== 'undefined' && translations['it'] && translations['it'][key]) {
        return translations['it'][key];
    }
    return fallback || key;
}
window.t = t;

function setLanguage(lang) {
    if (translations[lang]) {
        currentLang = lang;
        window.currentLang = lang;
        localStorage.setItem('appLang', lang);
        applyTranslations();
        updateFlagsUI();
        window.dispatchEvent(new CustomEvent('languageChanged', { detail: { lang } }));
    }
}
window.setLanguage = setLanguage;

function applyTranslations() {
    const elements = document.querySelectorAll('[data-i18n], [data-i18n-placeholder]');
    elements.forEach(el => {
        const key = el.getAttribute('data-i18n');
        const placeholderKey = el.getAttribute('data-i18n-placeholder');
        if (translations[currentLang] && translations[currentLang][key]) {
            // Per gestire gli elementi che hanno icone font-awesome (i tag <i>) e testo insieme
            let iconElement = el.querySelector('i');
            if (iconElement) {
                // Conserviamo l'icona e rimpiazziamo il resto
                el.innerHTML = '';
                el.appendChild(iconElement);
                el.appendChild(document.createTextNode(' ' + translations[currentLang][key]));
            } else if (el.id === 'welcome-title-container') {
                // Caso speciale per h1 Benvenuto che contiene uno span
                let spanElement = el.querySelector('#user-name-title');
                if (spanElement) {
                    el.innerHTML = translations[currentLang][key];
                    el.appendChild(spanElement);
                }
            } else {
                el.textContent = translations[currentLang][key];
            }
        }
        if (placeholderKey && translations[currentLang] && translations[currentLang][placeholderKey]) {
            el.setAttribute('placeholder', translations[currentLang][placeholderKey]);
        }
    });

    // Update slideshow text overlays dynamically
    document.querySelectorAll('[data-slide-text="true"]').forEach(el => {
        const textIt = el.getAttribute('data-text-it');
        const textEn = el.getAttribute('data-text-en');
        const textFr = el.getAttribute('data-text-fr');
        let newText = textIt;
        if (currentLang === 'en' && textEn) newText = textEn;
        if (currentLang === 'fr' && textFr) newText = textFr;
        if (newText) el.textContent = newText;
    });
}

function updateFlagsUI() {
    document.querySelectorAll('.lang-flag').forEach(flag => {
        if (flag.getAttribute('data-lang') === currentLang) {
            flag.style.opacity = '1';
            flag.style.border = '2px solid #10b981';
            flag.style.filter = 'grayscale(0)';
        } else {
            flag.style.opacity = '0.5';
            flag.style.border = '2px solid transparent';
            flag.style.filter = 'grayscale(0.8)';
        }
    });
}

document.addEventListener('DOMContentLoaded', () => {
    applyTranslations();
    updateFlagsUI();
    
    // Add event listeners to flags
    document.querySelectorAll('.lang-flag').forEach(flag => {
        flag.addEventListener('click', () => {
            setLanguage(flag.getAttribute('data-lang'));
        });
    });
});



